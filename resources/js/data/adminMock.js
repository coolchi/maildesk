/**
 * @param {Array<{id:string,accounts?:number}>} providers
 * @param {Array<{provider:string}>} accounts
 */
export function recountProviderTenants(providers, accounts) {
    const counts = {};
    for (const a of accounts) {
        if (!a.provider) continue;
        counts[a.provider] = (counts[a.provider] || 0) + 1;
    }
    for (const p of providers) {
        p.accounts = counts[p.id] || 0;
    }
    return providers;
}

/**
 * @param {{id:string,name:string,driver?:string,type?:string,config?:Array<{key:string,value:string}>,apiBase?:string|null}|null|undefined} provider
 */
export function smtpCredentialsForProvider(provider) {
    if (!provider) {
        return null;
    }

    const get = (key) =>
        provider.config?.find((c) => c.key === key)?.value ?? '';

    if (provider.driver === 'smtp' || provider.type === 'smtp') {
        return {
            mode: 'smtp',
            host: get('HOST') || 'smtp.example.com',
            port: Number(get('PORT') || 587),
            ports: [465, 587, 2587],
            username: get('USERNAME') || '',
            password: get('PASSWORD') || '••••••••',
            encryption: get('ENCRYPTION') || 'tls',
            label: provider.name,
            driver: provider.driver || 'smtp',
            apiBase: null,
        };
    }

    return {
        mode: 'api-relay',
        host: 'smtp.maildesk.test',
        port: 465,
        ports: [465, 587, 2587],
        username: 'maildesk',
        password: 'YOUR_API_KEY',
        encryption: 'tls',
        label: provider.name,
        driver: provider.driver || provider.type || 'api',
        apiBase: provider.apiBase || null,
    };
}

/**
 * @param {{provider:string}|null|undefined} account
 * @param {Array<{id:string,status:string}>} providers
 */
export function providerHealthForAccount(account, providers) {
    if (!account?.provider) {
        return { ok: false, reason: 'missing', provider: null };
    }
    const provider = providers.find((p) => p.id === account.provider) || null;
    if (!provider) {
        return { ok: false, reason: 'orphaned', provider: null };
    }
    if (provider.status !== 'active') {
        return { ok: false, reason: 'disabled', provider };
    }
    return { ok: true, reason: 'active', provider };
}
